"""Key, crop and bundle the SPIN LAB generated art (Codex image_gen via gpt-6-luna) into spin/art-bundle.js.
Sources: assets/spin/src/*.png (raw, kept). Outputs: assets/spin/*.png (game-ready) + spin/art-bundle.js (data URLs,
so WebGL can sample them from file:// as well). Missing sources are skipped; spin/sprites.js falls back to procedural art.
Usage: python tools/spin/bundle-art.py"""
import base64, io, json, pathlib
from PIL import Image
ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC, OUT = ROOT / 'assets/spin/src', ROOT / 'assets/spin'

def key_magenta(im):
    im = im.convert('RGBA'); px = im.load(); w, h = im.size
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            m = min(r, b) - g  # magenta-ness
            if m > 120: px[x, y] = (0, 0, 0, 0)
            elif m > 40:  # fringe: fade + despill
                k = (m - 40) / 80; px[x, y] = (int(r - (r - g) * k), g, int(b - (b - g) * k), int(a * (1 - k)))
    return im

def hero(im):
    im = im.convert('RGBA'); w, h = im.size
    if im.getpixel((5, 5))[3] > 0: im = key_magenta(im)
    # the separate swinging sword replaces the one held in the source: drop everything above the grip
    cut = int(h * 0.403); im.paste((0, 0, 0, 0), (0, 0, w, cut))
    cx, cy, half = int(w * 0.5), int(h * 0.622), int(h * 0.383)  # pivot = head centre
    return im.crop((cx - half, cy - half, cx + half, cy + half)).resize((256, 256), Image.LANCZOS)

JOBS = {
    'hero':  ('hero_top.png', hero),
    'item':  ('item_crystal.png', lambda im: (key_magenta(im) if im.convert('RGBA').getpixel((5, 5))[3] and im.convert('RGB').getpixel((5, 5))[1] < 60 and im.convert('RGB').getpixel((5, 5))[0] > 200 else im.convert('RGBA')).resize((192, 192), Image.LANCZOS)),
    'sword': ('sword_big.png', lambda im: (lambda k: k.crop(k.getchannel('A').getbbox()).resize((128, 384), Image.LANCZOS))(key_magenta(im))),
    'floor': ('arena_floor.png', lambda im: im.convert('RGB').resize((512, 512), Image.LANCZOS)),
    'ice':   ('ice_body.png', lambda im: im.convert('RGB').resize((256, 256), Image.LANCZOS)),
    'icex':  ('ice_xsec.png', lambda im: im.convert('RGB').resize((256, 256), Image.LANCZOS)),
}
bundle, manifest = {}, {}
for name, (src, fn) in JOBS.items():
    p = SRC / src
    if not p.exists(): continue
    out = fn(Image.open(p)); out.save(OUT / (name + '.png'), optimize=True)
    buf = io.BytesIO(); out.save(buf, 'PNG', optimize=True)
    bundle[name] = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
    manifest[name] = {'source': 'assets/spin/src/' + src, 'size': out.size, 'bytes': buf.tell(), 'generator': 'codex exec -m gpt-6-luna (built-in image_gen)'}
(ROOT / 'spin/art-bundle.js').write_text('/* generated by tools/spin/bundle-art.py from assets/spin/src (Codex image_gen via gpt-6-luna) */\nwindow.SPIN_ART=' + json.dumps(bundle) + ';\n', encoding='utf8')
(OUT / 'manifest.json').write_text(json.dumps(manifest, indent=1), encoding='utf8')
print({k: v['bytes'] for k, v in manifest.items()})
